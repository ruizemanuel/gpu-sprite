/** A 16×16 1-bit bitmap from 16 rows of 16 characters: "#" is on. */
function bits(rows: string[]): Uint8Array {
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error("a tile needs 16 rows of 16 characters");
  return Uint8Array.from(rows.join(""), (c) => (c === "#" ? 1 : 0));
}

